"""Generate the checked-in settings reference from typed definition metadata."""
from __future__ import annotations

import argparse
from dataclasses import fields
import json
from pathlib import Path
from typing import Any

from app.pipelines.catalog import load_catalog
from app.pipelines.resolver import RELEASED_AGENT_FALLBACKS, resolve
from app.settings_definitions import AgentSettings, RuntimeLimits, runtime_settings_manifest

ROOT = Path(__file__).resolve().parents[1]
REFERENCE = ROOT / 'docs/langgraph-pipeline-settings.md'


def display(value: Any) -> str:
    return '`' + json.dumps(value, ensure_ascii=False).replace('|', '\\|') + '`'


def render_reference(pipeline: str = 'v2.16', overrides: dict[str, Any] | None = None) -> str:
    resolved = resolve(pipeline, overrides)
    released = load_catalog().get(pipeline)['agent']
    lines = [
        '# Pipeline settings reference', '',
        '<!-- Generated by python -m app.settings_reference; do not edit this file by hand. -->', '',
        f'v2.17 migration reference; represented released pipeline: **{pipeline}**. '
        'This is settings centralization only; the graph has not been implemented.', '',
        'Definitions, units, validation and explanations come from '
        '[settings_definitions.py](../app/settings_definitions.py). '
        'Released values remain in [the catalog](../pipelines.md); explicit overrides are applied by '
        '[the resolver](../app/pipelines/resolver.py). Current defaults do not replace released values.', '',
        f'Effective example: pipeline `{pipeline}`, explicit overrides {display(overrides or {})}. '
        'This table describes that example, not every running service.', '',
        '## Agent settings', '',
        '| Setting | Default | Released value | Effective value | Units | Meaning / validation | Source |',
        '|---|---|---|---|---|---|---|',
    ]
    for item in fields(AgentSettings):
        definition = item.metadata['definition']
        if item.name in released:
            released_value = display(released[item.name])
        else:
            released_value = display(RELEASED_AGENT_FALLBACKS[pipeline][item.name]) + ' (released omission; resolver fallback)'
        constraints = []
        if definition.minimum is not None:
            constraints.append(f'minimum {definition.minimum:g}')
        if definition.maximum is not None:
            constraints.append(f'maximum {definition.maximum:g}')
        if definition.choices:
            constraints.append('choices: ' + ', '.join(definition.choices))
        meaning = definition.explanation + (' Validation: ' + '; '.join(constraints) + '.' if constraints else '')
        lines.append(f'| `{item.name}` | {display(item.default)} | {released_value} | '
                     f'{display(getattr(resolved.agent_settings, item.name))} | {definition.unit} | '
                     f'{meaning} | [{definition.source}](../{definition.source}) |')
    lines += ['', '## Embedded runtime limits', '',
              'These limits were not fields in the released catalog. They retain their existing effective '
              'values and have no new user override surface. They are recorded separately in experiment '
              'manifests and answer-cache identity; they are not silently presented as catalog-pinned settings.', '',
              '| Setting | Default | Effective value | Runtime units | Meaning | Source |',
              '|---|---|---|---|---|---|']
    effective = runtime_settings_manifest()
    for item in fields(RuntimeLimits):
        definition = item.metadata['definition']
        meaning = definition.explanation
        if definition.approximate_tokens:
            meaning += f' Display-only estimate: approximately {effective[item.name] / 4:,.0f} tokens at four characters/token.'
        lines.append(f'| `{item.name}` | {display(item.default)} | {display(effective[item.name])} | '
                     f'{definition.unit} | {meaning} | [{definition.source}](../{definition.source}) |')
    lines += ['', '## Reproduction and identity', '',
              'Regenerate with `python -m app.settings_reference`; verify with '
              '`python -m app.settings_reference --check`. '
              'For an effective provider/override example, use `--settings-json` and `--output` '
              'to write a separate reference without replacing this default example.', '',
              'Compaction and clipping still count characters. Token estimates are explanatory only; '
              'they do not truncate requests, change evidence selection, or guarantee a context bound. '
              'The protected conversation handoff is unchanged.', '',
              'All resolved agent values remain in run manifests and cache identity. '
              'The effective embedded runtime limits now also appear under `runtime_settings` in the '
              'pipeline manifest and exact-answer cache identity. Legacy answer entries without this '
              'dimension are conservatively excluded from reuse. Released pipeline IDs/checksums are '
              'unchanged; source manifests distinguish this code revision. Retrieval configuration '
              'and model identities continue to be recorded by the existing pipeline config manifest.', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--pipeline', default='v2.16')
    parser.add_argument('--settings-json', default='{}', help='Explicit resolver overrides as a JSON object')
    parser.add_argument('--output', type=Path, default=REFERENCE)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = render_reference(args.pipeline, json.loads(args.settings_json))
    if args.check:
        if args.output.read_text() != source:
            parser.exit(1, f'{args.output} is stale; regenerate the settings reference\n')
    else:
        args.output.write_text(source)


if __name__ == '__main__':
    main()
