"""Generate the human-readable v2.17 graph directly from compiled nodes and edges."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from app.agent.graph import build_graph
from app.pipelines.catalog import load_catalog

REFERENCE = Path(__file__).resolve().parents[2] / 'docs/langgraph-execution-graph.md'
LABELS = {
    '__start__': 'Start',
    'prepare': 'Prepare question and initial evidence',
    'decide': 'Another model turn allowed?',
    'select': 'Ask existing provider for next action',
    'tools': 'Process reply tools sequentially',
    'review': 'Review answer text',
    'budget': 'Draft from conversation handoff',
    'final': 'Prepare final answer and result',
    '__end__': 'End',
}


def render_reference() -> str:
    catalog = load_catalog()
    topology = build_graph().get_graph()
    lines = [
        '# Implemented v2.17 execution graph', '',
        '<!-- Generated by python -m app.agent.graph_reference; do not edit by hand. -->', '',
        f'Target: **v2.17 candidate**, explicitly registered. Released catalog default: **{catalog.default}**. '
        'Explicit v2.17 resolution routes through `app.agent.execution.run_agent`; the default and '
        'the released `app.agent.runner.run_agent` remain unchanged. Live acceptance and deployment are pending.', '',
        'The diagram contains the actual compiled nodes and edges. Branch labels are the route '
        'values emitted by the extracted boundaries, not extra model calls or separate agents.', '',
        '```mermaid', 'flowchart TD',
        f'    subgraph signature["v2.17 candidate — {catalog.default} released baseline"]',
    ]
    for name in topology.nodes:
        label = json.dumps(LABELS[name], ensure_ascii=False)
        shape = '{' + label + '}' if name == 'decide' else '[' + label + ']'
        lines.append(f'    {name}{shape}')
    for edge in topology.edges:
        annotation = f'|{edge.data}|' if edge.data else ''
        lines.append(f'    {edge.source} -->{annotation} {edge.target}')
    lines += ['    end', '```', '',
              'Tool processing handles one entire model reply in order. Rejected verification and '
              'previously rejected answers can continue within that node and bypass that call’s '
              'ordinary tool-budget check. Accepted submission skips remaining calls. Text review '
              'has its existing distinct nudge, coverage and verification rules.', '',
              'Timeout, turn and tool exits reach budget drafting and then shared final preparation. '
              'The final result still reports `stopped=budget` for those exits. The `done` route '
              'terminates the graph. Provider exceptions propagate; recoverable tool errors stay '
              'observations. There is no automatic retry or universal fallback.', '',
              'For T permitted model-selection turns, the longest path executes '
              '`1 + 3*T + 1 + 1 + 1 = 3*T + 4` nodes: preparation; T decide/select/review-or-tools '
              'cycles; the final turn-budget decision; budget drafting; final preparation. '
              'The invocation uses `recursion_limit = 3*T + 5`, allowing one additional framework '
              'halt step. Tool count does not add graph transitions because tools execute within '
              'one node. Application budgets, not the framework limit, select the handoff.', '',
              'The graph carries the existing in-memory `ExecutionState` in a single channel and '
              'receives `AgentRuntime` through LangGraph runtime context. No message reducer, '
              'checkpoint, persistent store, prebuilt agent or parallel tool node is used.', '',
              'Regenerate with `python -m app.agent.graph_reference`; check with '
              '`python -m app.agent.graph_reference --check`. '
              'Node implementations are in [execution.py](../app/agent/execution.py); '
              'graph wiring and the limit are in [graph.py](../app/agent/graph.py). '
              'Graph/node spans surround actual execution, and the answering/cache/experiment '
              'boundaries support an explicitly identified graph run. Candidate registration '
              'and live trace acceptance remain later roadmap steps.', '']
    return '\n'.join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = render_reference()
    if args.check:
        if REFERENCE.read_text() != source:
            parser.exit(1, 'Graph reference is stale; regenerate with python -m app.agent.graph_reference\n')
    else:
        REFERENCE.write_text(source)


if __name__ == '__main__':
    main()
